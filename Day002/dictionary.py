# Dictionary in Python

student = {
    "name": "Alice",
    "age": 20,
    "course": "Python"
}
print(student)

print(type(student))

student = {
    "name": "Alice",
    "age": 20,
    "course": "Data Science"
}
print(student)

student["city"] = "New York"

print(student)

del student["city"]

print(student)

student = {
    "name": "Henry",
    "age": 25,
    "country": "Kenya",
    "county": "Kiambu",
    "village": "Juja",
    "course": "Python"
}

print(student)

student ["city"] = "Nairobi"

print(student)